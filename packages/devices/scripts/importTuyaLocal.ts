// Converts tuya-local's device files, and this package's own in devices/,
// into src/catalog/, and lists the tuya-local files it cannot convert in the
// repository's UNSUPPORTED.md.
//
//   pnpm --filter @open-tuya/devices import-catalog <tuya-local checkout>

import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { convertDeviceFile } from "./convert.ts";

const DEVICES_FOLDER = "custom_components/tuya_local/devices";
const REPOSITORY = "https://github.com/make-all/tuya-local";
const OWN_DEVICES_FOLDER = "packages/devices/devices";
const OWN_REPOSITORY = "https://github.com/cheziyi/open-tuya";
const UNSUPPORTED_START =
  "<!-- Generated by packages/devices/scripts/importTuyaLocal.ts. -->";
const UNSUPPORTED_END = "<!-- End of generated list. -->";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "../..");
const catalogFolder = join(packageRoot, "src/catalog");

const checkout = process.argv[2];
if (!checkout) {
  throw new Error("Pass the path of a tuya-local checkout");
}

/** Where device files come from: tuya-local's checkout, or this repository. */
interface DeviceSource {
  root: string;
  folder: string;
  repository: string;
  /** A file of this package's own must convert, where tuya-local's is listed
   * in UNSUPPORTED.md, and must be committed, so that its entry records the
   * commit that last changed it. */
  own: boolean;
}

const sources: readonly DeviceSource[] = [
  {
    root: checkout,
    folder: DEVICES_FOLDER,
    repository: REPOSITORY,
    own: false,
  },
  {
    root: repositoryRoot,
    folder: OWN_DEVICES_FOLDER,
    repository: OWN_REPOSITORY,
    own: true,
  },
];

rmSync(catalogFolder, { recursive: true, force: true });
mkdirSync(catalogFolder);
const modules: string[] = [];
const unsupported = new Map<string, string[]>();
const counts = { tuyaLocal: 0, own: 0 };
for (const source of sources) {
  const folder = join(source.root, source.folder);
  const files = existsSync(folder)
    ? readdirSync(folder)
        .filter((file) => file.endsWith(".yaml"))
        .sort()
    : [];
  const commits = lastCommits(source.root, source.folder);
  for (const file of files) {
    const text = readFileSync(join(folder, file), "utf8");
    const conversion = convertDeviceFile(text);
    if ("unsupported" in conversion) {
      if (source.own) {
        throw new Error(
          `${source.folder}/${file} uses ${conversion.unsupported}, which the conversion does not take`,
        );
      }
      const devices = unsupported.get(conversion.unsupported) ?? [];
      devices.push(file);
      unsupported.set(conversion.unsupported, devices);
      continue;
    }
    const commit = commits.get(file);
    if (!commit) {
      throw new Error(
        source.own
          ? `Commit ${source.folder}/${file} before running the script: its entry records the commit that last changed it`
          : `No commit changed ${file}`,
      );
    }
    const module = moduleName(file);
    if (modules.includes(module)) {
      throw new Error(
        `${source.folder}/${file} names the module of another device file, ${module}${source.own ? ": remove it once tuya-local lists the device" : ""}`,
      );
    }
    modules.push(module);
    if (source.own) {
      counts.own++;
    } else {
      counts.tuyaLocal++;
    }
    const copyright = text
      .split("\n")
      .filter((line) => /^#\s*(Copyright|SPDX-License-Identifier)/.test(line))
      .map((line) => `// ${line.replace(/^#\s*/, "")}`);
    writeFileSync(
      join(catalogFolder, `${module}.ts`),
      [
        `// Generated by scripts/importTuyaLocal.ts from`,
        `// ${source.repository}/blob/${commit}/${source.folder}/${encodeURIComponent(file)}.`,
        "// Do not edit: run the script again.",
        ...copyright,
        'import type { TuyaDeviceEntry } from "../entry.js";',
        "",
        `const entry: TuyaDeviceEntry = ${JSON.stringify({ ...conversion.entry, source: { file, commit } })};`,
        "",
        "export default entry;",
        "",
      ].join("\n"),
    );
  }
}
writeFileSync(
  join(catalogFolder, "index.ts"),
  [
    "// Generated by scripts/importTuyaLocal.ts. Do not edit: run the script again.",
    'import type { TuyaDeviceEntry } from "../entry.js";',
    ...modules.map(
      (module) => `import device_${module} from "./${module}.js";`,
    ),
    "",
    "/** Every device the catalog describes. */",
    `export const CATALOG: readonly TuyaDeviceEntry[] = [${modules.map((module) => `device_${module}`).join(", ")}];`,
    "",
  ].join("\n"),
);
writeUnsupported(unsupported);
execFileSync("pnpm", ["exec", "biome", "check", "--write", catalogFolder], {
  cwd: repositoryRoot,
  stdio: "inherit",
});
const skipped = [...unsupported.values()].reduce(
  (sum, devices) => sum + devices.length,
  0,
);
console.log(
  `Converted ${counts.tuyaLocal} of ${counts.tuyaLocal + skipped} tuya-local device files, ${skipped} listed in UNSUPPORTED.md, and ${counts.own} of this package's own.`,
);

/** The commit that last changed each device file in a folder of a
 * repository, from one walk of the folder's history. */
function lastCommits(root: string, folder: string): Map<string, string> {
  const log = execFileSync(
    "git",
    ["-C", root, "log", "--format=commit %H", "--name-only", "--", folder],
    { encoding: "utf8", maxBuffer: 1024 * 1024 * 1024 },
  );
  const commits = new Map<string, string>();
  let commit = "";
  for (const line of log.split("\n")) {
    if (line.startsWith("commit ")) {
      commit = line.slice("commit ".length);
    } else if (line.startsWith(`${folder}/`)) {
      const file = line.slice(folder.length + 1);
      if (!commits.has(file)) {
        commits.set(file, commit);
      }
    }
  }
  return commits;
}

function moduleName(file: string): string {
  return file
    .replace(/\.yaml$/, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_");
}

function writeUnsupported(unsupported: Map<string, string[]>): void {
  const path = join(repositoryRoot, "UNSUPPORTED.md");
  const text = readFileSync(path, "utf8");
  const start = text.indexOf(UNSUPPORTED_START);
  const end = text.indexOf(UNSUPPORTED_END);
  if (start === -1 || end === -1) {
    throw new Error(`UNSUPPORTED.md lacks the markers of the generated list`);
  }
  const rows = [...unsupported.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([feature, devices]) =>
        `| ${feature} | ${devices.length} | ${devices.map((device) => device.replace(/\.yaml$/, "")).join(", ")} |`,
    );
  const list = [
    UNSUPPORTED_START,
    "",
    "| tuya-local feature | Devices | Device files |",
    "| --- | --- | --- |",
    ...rows,
    "",
    UNSUPPORTED_END,
  ].join("\n");
  writeFileSync(
    path,
    text.slice(0, start) + list + text.slice(end + UNSUPPORTED_END.length),
  );
}
